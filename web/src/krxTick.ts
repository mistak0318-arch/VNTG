/**
 * **호가 단위와 전일 대비** — KRX 2023-01 개편 기준.
 *
 * `OrderPage` 안에만 있던 `tickOf` 를 꺼내 왔다 (2026-10-15). 주문 말고도 쓸 데가
 * 생겼기 때문이다 — 시세분석 표에서 **등락률 밑에 「얼마 빠졌나」**를 적는 데 쓴다.
 */
export function tickOf(p: number): number {
  if (p < 2_000) return 1;
  if (p < 5_000) return 5;
  if (p < 20_000) return 10;
  if (p < 50_000) return 50;
  if (p < 200_000) return 100;
  if (p < 500_000) return 500;
  return 1_000;
}

/**
 * **전일 대비(원)** — 현재가와 등락률에서 되돌려 낸다.
 *
 * 벤티지: "등락률 밑에 얼마 빠진 건지 금액 좀 조그만 글씨로" (키움 관심종목 캡처).
 *
 * ## 왜 되돌려 내나
 *
 * 순위 조회 응답에는 **대비 칸이 없다**(`code·name·cur_prc·flu_rt·…`). 그 한 칸을
 * 받자고 종목마다 조회를 더 거는 것은 말이 안 되고, 현재가와 등락률만 있으면
 * 산수로 나온다 — `기준가 = 현재가 ÷ (1 + 등락률)`, 대비는 그 차이다.
 *
 * ## ⚠️ 격자에 맞추는 것은 **기준가**다 (2026-10-15 두 번째 고침)
 *
 * 등락률이 **소수 둘째 자리까지만** 오므로 그냥 빼면 몇 원씩 어긋난다. 그래서 호가
 * 단위로 맞추는데, 처음에는 **현재가의 호가**로 맞췄다. 벤티지가 "아무리 반올림했어도
 * 숫자가 조금씩 안 맞는 것 같은데" 하길래 순위 응답 **2,274줄로 전수 측정**했더니
 * 두 군데가 틀리고 있었다.
 *
 * **① 밴드를 넘나드는 종목.** 현재가와 기준가가 다른 호가 구간에 있으면 현재가 쪽
 * 격자는 남의 자가 된다 — TPC로보틱스 5,220(+17.7%)의 기준가는 4,435(5원 구간)인데
 * 현재가 구간(10원)으로 맞춰 4,440 이 됐다. 격자에 **실제로 서 있는 것은 기준가**이므로
 * 기준가 자신의 구간으로 맞춘다.
 *
 * **② ETF.** 측정으로 갈렸다 — 412개 ETF 의 역산 기준가는 **1원 격자**에 떨어진다
 * (잔차 평균 0.25·최대 0.5). 가격대별 호가로 맞추면 평균 23원, 최대 480원까지 어긋난다
 * (KODEX CD금리액티브 107만원대에서 437원). ETF 는 1원으로 둔다.
 *
 * 전수 측정 결과(잔차 = 역산 기준가가 격자에서 벗어난 정도):
 *
 *   ETF    평균 23.32 → **0.24** · 최대 479.9 → **0.5**
 *   일반주  최대 482 → **94** · 반호가 넘게 틀린 줄 16/1862 → **2/1862**
 *
 * ## 남는 오차
 *
 * 일반주 두 줄이 남는다. 등락률이 소수 둘째 자리뿐이라 **비싼 주식일수록 역산 오차가
 * 커지기** 때문이다(140만원짜리면 ±70원). 호가 한 칸 안이라 표시값은 거의 늘 맞지만,
 * **원리상 어림값**이라는 것은 적어 둔다 — 정확한 대비가 응답에 오는 화면
 * (`pred_pre` 가 있는 곳)에서는 이 함수를 쓰지 않는다.
 */
export function diffFromRate(
  price: number | null | undefined,
  rate: number | null | undefined,
  opts?: { etf?: boolean },
): number | null {
  if (price == null || rate == null) return null;
  const p = Math.abs(Number(price));
  const r = Number(rate);
  if (!Number.isFinite(p) || !Number.isFinite(r) || p <= 0) return null;
  /* −100% 는 기준가가 0 이라는 뜻이라 나눌 수 없다 */
  if (r <= -100) return null;
  const base = p / (1 + r / 100);
  /* ⚠️ 현재가가 아니라 **기준가**의 호가로 맞춘다 — 위 ① */
  const t = opts?.etf ? 1 : tickOf(base);
  return p - Math.round(base / t) * t;
}
