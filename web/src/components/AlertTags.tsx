export function AlertTags({ alerts, compact }: { alerts?: SignalAlerts | null; compact?: boolean }) {
  if (!alerts || (alerts.hot.length === 0 && alerts.late.length === 0)) return null;
  const tip = (kind: "hot" | "late", items: SignalAlerts["hot"]) =>
    (kind === "hot"
      ? "🔥 쏠림 — 뜨거운 날의 뜨거운 종목. 20일 뒤 시장에 졌다(장세 무관). 점수는 그대로고 표시만 합니다.\n\n"
      : "⏳ 늦음 — 이미 많이 오른 자리. 약세장(급락 뒤 장)에서만 표시합니다 — 강세장에선 오르는 애가 계속 오릅니다.\n\n") +
    items.map((a) => `• ${a.label}\n  ${WHY[a.key] ?? ""}`).join("\n\n");
  return (
    <span className={`sig-alerts${compact ? " compact" : ""}`}>
      {alerts.hot.length > 0 && (
        <span className="sig-alert hot" title={tip("hot", alerts.hot)}>
          🔥{compact ? alerts.hot.length : " " + alerts.hot.map((a) => a.label).join(" · ")}
        </span>
      )}
      {alerts.late.length > 0 && (
        <span className="sig-alert late" title={tip("late", alerts.late)}>
          ⏳{compact ? alerts.late.length : " " + alerts.late.map((a) => a.label).join(" · ")}
        </span>
      )}
    </span>
  );
}

