/**
 * **눌린 글을 다시 줄로 세운다** (2026-10-09).
 *
 * 벤티지: "텔레그램 글 읽을 때 이게 줄정리라는 게 안 돼 있어서 좀 보기가 힘든데
 * 이거 가독성 있게 개편 좀 안 되려나?"
 *
 * 서버가 버즈 표본을 저장할 때 `\s+ → " "` 로 줄바꿈을 지우고 있었다. 오늘부터는 안 지우지만
 * **이미 저장된 글은 못 되살린다** — 그 글자들은 이미 한 줄이다.
 *
 * 다행히 텔레그램 글은 생김새가 일정하다. 「… 정리 : 항목 : 항목 → 설명」처럼 `:` 과 `→` 가
 * 원래 줄머리였다. 그 자리를 다시 줄로 끊으면 원래 모양에 거의 돌아온다.
 *
 * ⚠️ **줄바꿈이 하나라도 있으면 손대지 않는다.** 그건 원문이 제 모양을 갖고 있다는 뜻이고,
 * 거기에 이 규칙을 또 걸면 멀쩡한 글을 잘게 부순다. 그래서 이 함수는 새 글이 쌓일수록
 * 하는 일이 줄다가 저절로 쓸모가 없어진다 — 고침이 아니라 **옛 글을 위한 임시 다리**다.
 */

/** 줄머리였을 자리 — 공백 뒤의 `:` 와 화살표들 */
const HEAD = /\s+(?=[:：]\s)|\s+(?=[→▶➡]\s?)/gu;

export function msgFlow(text: string): string {
  if (!text) return text;
  /* 제 모양이 살아 있으면 그대로 — 건드리는 것이 손해다 */
  if (text.includes("\n")) return text;
  const out = text.replace(HEAD, "\n").trim();
  /*
   * 끊고 보니 줄이 둘도 안 되면 원래 그런 글이다(한 문장짜리 속보 따위).
   * 괜히 바꾼 티만 내지 말고 원문을 돌려준다.
   */
  return out.split("\n").length >= 2 ? out : text;
}
