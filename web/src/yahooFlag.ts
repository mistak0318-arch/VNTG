/**
 * 심볼 하나의 깃발. 점이 없으면 미국(야후는 미국 종목에 꼬리를 안 붙인다),
 * 아는 꼬리면 그 나라, 모르면 빈 문자열.
 */
export function flagOfSymbol(symbol: string): string {
  const s = String(symbol ?? "").trim().toUpperCase();
  if (!s) return "";
  const i = s.lastIndexOf(".");
  if (i < 0) return "🇺🇸";
  return BY_SUFFIX[s.slice(i + 1)] ?? "";
}
