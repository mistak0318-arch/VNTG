/**
 * 업종을 **실제로 하는 일**에 맞춘다.
 *
 * ## 무엇이 문제였나
 *
 * 「금융에 에코프로가 있다」는 말이 나왔다. 확인해 보니 키움이 틀린 게 아니라 **한국거래소
 * 분류가 지주회사를 금융업에 넣는다.** 시가총액 상위 300 종목에서 「금융」으로 잡힌 21개
 * 가운데 **19개가 지주사**였고 진짜 금융회사는 삼성카드·미래에셋벤처투자 둘뿐이었다.
 * 보험(11)과 증권(10)은 애초에 따로 있으니, 「금융」은 사실상 **지주사 바구니**다.
 *
 * 그러면 업종 수급도 테마 MAP 도 뜻이 흐려진다 — 「오늘 금융이 세다」가 실제로는
 * 「지주사가 세다」인데 그 둘은 다른 이야기다.
 *
 * ## 어떻게 고치나
 *
 *   1. **한 가지 사업이 뚜렷한 지주사**는 그 사업 업종으로 옮긴다. 에코프로는 2차전지고
 *      한미사이언스는 제약이다 — 시장도 그렇게 보고 그렇게 움직인다.
 *   2. **여러 사업을 거느린 지주사**는 「지주」라는 자리를 새로 만들어 거기 둔다.
 *      SK 를 반도체라 할지 에너지라 할지는 답이 없다. 억지로 하나를 고르느니 지주사끼리
 *      묶는 게 낫다 — 배당·자사주 같은 이슈에 실제로 **같이 움직인다.**
 *
 * ## ⚠️ 코드는 전부 실측했다
 *
 * 처음에 기억으로 적었다가 **오리온홀딩스를 271560 으로 잘못 쓴 것**을 검증에서 잡았다
 * (실제 001800). 아래 코드는 모두 `/api/rank/market-cap` 응답에서 그대로 옮긴 것이다.
 * 새로 넣을 때도 **검색으로 확인하고** 넣는다 — 종목코드는 외워서 쓸 것이 못 된다.
 *
 * 여기 없는 종목은 **키움이 준 그대로** 둔다. 모르는 것을 지어내지 않는다.
 */

/**
 * 한 가지 사업이 뚜렷한 지주사 — 그 업종으로 옮긴다.
 *
 * 업종 이름은 키움이 쓰는 것을 그대로 쓴다(「전기/전자」·「제약」…). 새 이름을 만들면
 * 업종 MAP 에서 혼자 떨어져 나온다.
 */
const AS_BUSINESS: Record<string, string> = {
  "086520": "전기/전자", // 에코프로 — 2차전지 소재
  "008930": "제약", // 한미사이언스 — 한미약품 지주
  "009540": "운송장비/부품", // HD한국조선해양 — 조선
  "010060": "화학", // OCI홀딩스
  "006260": "금속", // LS — 전선·소재
  "003380": "음식료/담배", // 하림지주
  "001800": "음식료/담배", // 오리온홀딩스
  "006040": "음식료/담배", // 동원산업
  "0126Z0": "제약", // 삼성에피스홀딩스 — 삼성바이오에피스 지주
};

/**
 * 여러 사업을 거느려 하나로 못 고르는 지주사 — 「지주」로 묶는다.
 *
 * ⚠️ CJ 는 식품·물류·엔터를 함께 거느린다. 음식료로 넣을까 했지만 **하나를 고를 근거가
 * 없어** 여기 뒀다. 쓰면서 어느 쪽이 편한지 보고 옮기면 된다.
 */
const AS_HOLDING = new Set([
  "034730", // SK
  "003550", // LG
  "001040", // CJ
  "004800", // 효성
  "004990", // 롯데지주
  "000240", // 한국앤컴퍼니
  "009970", // 영원무역홀딩스
  "005440", // 현대지에프홀딩스
  "012630", // HDC
  "006120", // SK디스커버리
]);

/** 새로 만든 업종 이름 */
export const HOLDING_SECTOR = "지주";

/**
 * 업종 이름을 고친다.
 *
 * @param code 6자리 종목코드(접미사가 붙어 있어도 된다)
 * @param sector 키움이 준 업종명
 */
export function fixSector(code: string, sector: string): string {
  const c = String(code ?? "").replace(/_(AL|NX)$/i, "").trim();
  const business = AS_BUSINESS[c];
  if (business) return business;
  if (AS_HOLDING.has(c)) return HOLDING_SECTOR;
  return sector;
}

/** 우리가 고친 종목인가 — 화면에서 「왜 다르지」에 답하려고 둔다 */
export function isSectorFixed(code: string): boolean {
  const c = String(code ?? "").replace(/_(AL|NX)$/i, "").trim();
  return c in AS_BUSINESS || AS_HOLDING.has(c);
}
