/** 새로 만든 업종 이름 */
export const HOLDING_SECTOR = "지주";

/**
 * 업종 이름을 고친다.
 *
 * @param code 6자리 종목코드(접미사가 붙어 있어도 된다)
 * @param sector 키움이 준 업종명
 */
export function fixSector(code: string, sector: string): string {
  const c = String(code ?? "").replace(/_(AL|NX)$/i, "").trim();
  const business = AS_BUSINESS[c];
  if (business) return business;
  if (AS_HOLDING.has(c)) return HOLDING_SECTOR;
  return sector;
}

/** 우리가 고친 종목인가 — 화면에서 「왜 다르지」에 답하려고 둔다 */
export function isSectorFixed(code: string): boolean {
  const c = String(code ?? "").replace(/_(AL|NX)$/i, "").trim();
  return c in AS_BUSINESS || AS_HOLDING.has(c);
}

/**
 * **대분류 업종** — 소분류가 있으면 소분류에 진다 (2026-10-23).
 *
 * 벤티지: "주도주 메뉴도 같이 보고". 열어 보니 **빅텍이 「의료/정밀기기」, LS에코에너지가
 * 「금융」, 삼성전기가 「제조」**로 잡혀 있었다. 그리고 바로 **어제 스냅샷에서 삼성전기는
 * 「전기/전자」**였다 — 같은 종목의 업종이 날마다 바뀐 것이다.
 *
 * 까닭: 한국거래소 업종에는 **「제조업」·「금융업」 같은 대분류가 소분류와 나란히** 있다.
 * 제조업은 음식료·섬유·화학·금속·기계·전기전자·의료정밀·운수장비를 다 품고, 금융업은
 * 은행·증권·보험을 품는다. 그래서 삼성전기는 「전기/전자」와 「제조」 **양쪽에 다 뜬다.**
 *
 * 스냅샷은 업종을 하나씩 훑어 **먼저 온 쪽을 유지**했는데, 업종 목록이 오는 순서가
 * 고정이 아니라 그날그날 달라진다. 그래서 어제는 소분류, 오늘은 대분류가 이겼다.
 * 실측 분포에서 「제조」가 **429 종목으로 1위**(전기/전자 180)인 것이 그 증거다.
 *
 * ⚠️ **대분류를 버리지는 않는다.** 소분류가 없는 종목은 대분류가 유일한 답이다
 * (코스닥 쪽에 그런 종목이 많다). 「대분류만 있으면 쓰고, 소분류가 오면 양보한다」가
 * 맞는 규칙이다 — `marketSnapshot.build` 가 이 함수로 그 판단을 한다.
 */
const BROAD_SECTORS = new Set(["제조", "금융"]);

/** 이 업종 이름이 대분류인가 — 같은 종목에 소분류가 또 오면 그쪽에 자리를 내준다 */
export function isBroadSector(name: string): boolean {
  return BROAD_SECTORS.has(String(name).trim());
}
