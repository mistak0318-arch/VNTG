/**
 * 저장본과 기본값을 합친다.
 *
 * **통째로 덮어쓰면 안 된다.** 예전 저장본에는 `axis` 도 `strongAt` 도 없다 —
 * 저장된 항목을 그대로 쓰면 축이 없는 기준이 생겨 화면이 무너진다.
 * 그래서 **뼈대는 기본값에서, 사용자가 정한 값(켬/끔·가중치·기준값)만 저장본에서** 가져온다.
 */
function mergeConfig(saved: Partial<SignalConfig> | null): SignalConfig {
  const savedChecks = new Map(
    (saved?.checks ?? []).map((c) => [c.key, c as Partial<CheckConfig>]),
  );
  return {
    ...DEFAULT_CONFIG,
    ...saved,
    /*
     * ⚠️ **옛 기본값(1/1/1)은 새 기본값으로 이사시킨다** (2026-08-31).
     *
     * 축 비중을 `1.5/1.3/0.6` 으로 바꾼 것은 **「며칠에서 몇 주를 보는 매매」에 맞춘
     * 설계 결정**이었다(위 DEFAULT_CONFIG 주석). 설정에 손잡이를 둔 것은 「바꾸고
     * 싶으면」이지 옛 값을 지키라는 뜻이 아니었다.
     *
     * 그런데 저장본이 옛 기본값 `1/1/1` 을 그대로 들고 있으면 병합에서 그것이 이겨
     * **새 설계가 적용되지 않는다.** 실측에서 그랬다 — 코드는 1.5/1.3/0.6 인데
     * 실제로는 1/1/1 로 돌고 있었다.
     *
     * 셋이 **모두 정확히 1** 이면 옛 기본값이지 사람이 고른 값이 아니다. 그때만
     * 이사시킨다. 하나라도 다르면 사람이 만진 것이므로 그대로 둔다 —
     * 추적기 모집단(60·200 → 300) 때와 같은 규칙이다.
     */
    axisWeights: (() => {
      const w = saved?.axisWeights;
      const oldDefault = w && w.trend === 1 && w.flow === 1 && w.value === 1;
      return oldDefault
        ? { ...DEFAULT_CONFIG.axisWeights }
        : { ...DEFAULT_CONFIG.axisWeights, ...(w ?? {}) };
    })(),
    checks: DEFAULT_CONFIG.checks.map((d) => {
      const s = savedChecks.get(d.key);
      if (!s) return d;
      /*
       * 업종 강세는 **저장분이 켜 두었어도 끈다** (2026-08-27).
       * 기본값만 바꾸면, 이미 저장된 설정을 쓰는 쪽(=실제로 쓰던 사람)에게는
       * 아무것도 안 바뀐다. 판정에서 빼기로 한 값이라 저장분보다 이 결정이 위다.
       */
      if (d.key === "sectorStrength") return { ...d, enabled: false, weight: 0 };
      return {
        ...d,
        enabled: typeof s.enabled === "boolean" ? s.enabled : d.enabled,
        weight: Number.isFinite(s.weight) ? Number(s.weight) : d.weight,
        threshold: Number.isFinite(s.threshold) ? Number(s.threshold) : d.threshold,
        // strongAt 은 예전 저장본에 없다. 없으면 기본값을 쓴다
        strongAt: Number.isFinite(s.strongAt) ? Number(s.strongAt) : d.strongAt,
        /*
         * 기간 — **기본값에 없는 기준에는 안 붙인다.**
         * 저장본이 엉뚱한 기준에 기간을 들고 있어도(옛 형식·손으로 고친 파일)
         * 기간 개념이 없는 기준에 값이 생기면 화면에 빈 칸이 뜬다.
         */
        span:
          d.span === undefined
            ? undefined
            : Number.isFinite(s.span) && Number(s.span) > 0
              ? Math.round(Number(s.span))
              : d.span,
      };
    }),
    maLines: normalizeMaLines(saved?.maLines ?? DEFAULT_CONFIG.maLines),
    regimeSwitch:
      typeof saved?.regimeSwitch === "boolean" ? saved.regimeSwitch : DEFAULT_CONFIG.regimeSwitch,
    bullAt:
      Number.isFinite(saved?.bullAt) && Number(saved?.bullAt) > 0 && Number(saved?.bullAt) < 100
        ? Number(saved?.bullAt)
        : DEFAULT_CONFIG.bullAt,
    /*
     * 0~1 밖은 안 받는다. 1 을 넘기면 아무것도 초록이 못 되고, 0 이면 규칙이 없는
     * 것과 같아 옛 상태로 조용히 돌아간다 — 둘 다 사람이 눈치채기 어렵다.
     */
    minCoverage:
      Number.isFinite(saved?.minCoverage) &&
      Number(saved?.minCoverage) >= 0 &&
      Number(saved?.minCoverage) <= 1
        ? Number(saved?.minCoverage)
        : DEFAULT_CONFIG.minCoverage,
    greenTo:
      Number.isFinite(saved?.greenTo) &&
      Number(saved?.greenTo) > 0 &&
      Number(saved?.greenTo) <= 100
        ? Number(saved?.greenTo)
        : DEFAULT_CONFIG.greenTo,
    /* 억. 0 은 「문턱 없음」이라 유효한 값이다 — 음수와 터무니없는 값만 막는다 */
    minTradeValue:
      Number.isFinite(saved?.minTradeValue) &&
      Number(saved?.minTradeValue) >= 0 &&
      Number(saved?.minTradeValue) <= 100_000
        ? Number(saved?.minTradeValue)
        : DEFAULT_CONFIG.minTradeValue,
  };
}

export async function getConfig(): Promise<SignalConfig> {
  if (configCache) return configCache;
  try {
    const saved = JSON.parse(await readFile(CONFIG_FILE, "utf-8")) as Partial<SignalConfig>;
    configCache = mergeConfig(saved);
  } catch {
    configCache = DEFAULT_CONFIG;
  }
  return configCache;
}

/**
 * 신호등 기준의 **지문** (2026-08-31 — signalTrack 에서 옮겨 왔다).
 *
 * 켠 기준·가중치·문턱·축 가중치까지 넣는다. 하나라도 바뀌면 다른 지문이 나오고,
 * 통계에서 「기준이 바뀐 뒤 것만」을 갈라 볼 수 있다.
 *
 * ## 왜 공용으로 옮겼나
 *
 * 추적기(`signalTrack`)에만 있었다. 그런데 **슈퍼신호등 원장에도 같은 문제**가 있다 —
 * 기준을 바꾸면 그 전 편입과 그 뒤 편입이 한 표에 섞이면서 평균이 뜻을 잃는다.
 * 두 곳이 **같은 지문**을 써야 「이 기록과 저 기록이 같은 기준인가」를 물을 수 있다.
 *
 * 사람이 읽을 값이 아니다 — **같은지 다른지**만 보면 된다.
 */
export async function configFingerprint(): Promise<string> {
  const c = await getConfig();
  const parts = [
    `g${c.greenAt}-${c.greenTo}y${c.yellowAt}`,
    /* 커버리지 문턱은 「무엇이 초록이 되나」를 통째로 바꾼다 — 지문에 반드시 넣는다 */
    `mc${c.minCoverage}`,
    /* 거래대금 하한도 마찬가지다 — 이걸 올리면 초록 집합이 통째로 달라진다 */
    `tv${c.minTradeValue}`,
    `r${c.riskYellowAt}-${c.riskRedAt}${c.riskBlocksGreen ? "B" : ""}`,
    /* 장세 전환은 점수를 통째로 바꾼다 — 지문에 없으면 「같은 설정」으로 오인된다 */
    `rg${c.regimeSwitch ? c.bullAt : "off"}`,
    `aw${c.axisWeights.trend}${c.axisWeights.flow}${c.axisWeights.value}`,
    `f${c.flowDays}`,
    `ma${c.maLines.join("")}`,
    ...c.checks
      .filter((x) => x.enabled)
      /* 기간도 지문에 넣는다 — 같은 문턱이라도 20일과 60일은 다른 기준이다 */
      .map((x) => `${x.key}:${x.weight}:${x.threshold}:${x.strongAt}${x.span ? `:${x.span}` : ""}`),
  ];
  let h = 0;
  const str = parts.join("|");
  for (let i = 0; i < str.length; i++) h = (h * 31 + str.charCodeAt(i)) | 0;
  return `c${(h >>> 0).toString(36)}`;
}

/**
 * **작을수록 좋은 기준** — 문턱이 만점보다 커도 맞바꾸지 않는다.
 *
 * 지금은 시가총액 하나다. 20일을 보는 매매에서 대형주는 덜 움직인다 —
 * 「위험」이 아니라 「먹을 게 없다」라서 실적 축에 그대로 두고 방향만 뒤집는다.
 */
const DESCENDING = new Set<CheckKey>(["marketCap"]);

export async function saveConfig(input: SignalConfig): Promise<SignalConfig> {
  const cfg = mergeConfig(input);
  /*
   * **두 값의 순서를 바로잡는다** (2026-08-31 점검).
   *
   * grade() 는 max/min 으로 정규화하므로 뒤집혀 있어도 점수는 맞다 — 그래서
   * 아무도 모른 채로 남는다. 문제는 화면이다: 「기준값 1000 → 아주 좋음 500」은
   * **500이 만점**으로 읽힌다. 실측에서 거래대금이 그렇게 저장돼 있었다.
   *
   * 값을 바꾸는 게 아니라 **자리를 맞바꾸는 것**이라 판정은 그대로다.
   * 위험 축도 같은 규칙이다 — 「위험 시작」이 「심각」보다 작아야 한다.
   *
   * ## ⚠️ 예외 — **작을수록 좋은 기준** (2026-09-01)
   *
   * 이 맞바꾸기가 「작을수록 좋다」를 **표현할 수 없게** 만들고 있었다. 시가총액이
   * 그 자리다 — 새 표본에서 뒤쪽 3천억 이하가 +5.48%p, 3~10조가 -3.01%p 로
   * **작을수록 좋은데**, 저장할 때마다 자리가 맞바뀌어 「클수록 좋다」로 되돌아갔다.
   *
   * 그래서 `DESCENDING` 에 든 기준만 맞바꾸지 않는다. 화면은 이 목록을 보고
   * 「작을수록 좋음」이라고 적는다 — 거꾸로 읽히는 것을 막으려던 원래 뜻은
   * 그대로 지키면서 표현력만 되찾는다.
   */
  for (const c of cfg.checks) {
    if (DESCENDING.has(c.key)) continue;
    if (c.threshold > c.strongAt) {
      const t = c.threshold;
      c.threshold = c.strongAt;
      c.strongAt = t;
    }
  }
  configCache = cfg;
  await mkdir(dirname(CONFIG_FILE), { recursive: true });
  await writeFile(CONFIG_FILE, JSON.stringify(cfg, null, 2), "utf-8");
  evalCache.clear(); // 기준이 바뀌면 기존 판정은 무효
  return cfg;
}

