export function isNotTheme(name: string): boolean {
  return (
    /레버리지|인버스|단일종목|2X|3X/i.test(name) ||
    /200|150|300|KRX|코스피|코스닥|KOSPI|KOSDAQ|MSCI|S&P|TOP\s*10\b/i.test(name) ||
    /커버드콜|배당|TR\b|채권|국고채|머니마켓|파킹/i.test(name)
  );
}

