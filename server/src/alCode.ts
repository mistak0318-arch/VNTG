/**
 * 통합(KRX+NXT) 종목코드 (2026-08-26).
 *
 * 키움 REST 는 종목코드 뒤에 `_AL` 을 붙이면 **KRX+NXT 통합** 값을 준다
 * (`_NX` 는 NXT 단독, 접미 없음은 KRX 단독).
 *
 * 실측(하이닉스 000660, 8/25): KRX 단독은 개인 +618,857·공매도 비중 4.59% 인데
 * 키움 앱(통합)은 +802,218·2.79% 였다 — NXT 몫이 통째로 빠져 「키움이랑 값이
 * 다르다」가 됐다. `_AL` 이 앱과 자리수까지 일치한다.
 *
 * **표시용 종목 데이터**(수급·공매도·거래원·시세표성·체결강도 등)에 쓴다.
 * 차트·신호등·백테스트·전종목 스냅샷은 KRX 기준으로 이력이 쌓여 있어 별도 결정.
 */
export function alCode(code: string): string {
  const bare = String(code ?? "").replace(/_(AL|NX)$/i, "");
  // 6자리 국내 종목코드만 — 다른 코드(업종·선물)에 붙이면 조회가 깨진다
  return /^\d{6}$/.test(bare) ? `${bare}_AL` : bare;
}
